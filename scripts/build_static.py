#!/usr/bin/env python3
"""Build the static version.

    python3 scripts/build_static.py

1. Turns data/event.json + data/guides.json into static/js/data.js
2. Inlines every stylesheet, script and vendored library into one
   self-contained file: dist/index.html

The result works from a double-click, a USB stick, GitHub Pages, Netlify — no
server, no build tools, no network.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "static"
DIST = ROOT / "dist" / "index.html"
DATA = ROOT / "data"


def load_json(path: Path, fallback):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"  ! could not read {path.name}: {exc}")
        return fallback


def write_data_js(event: dict, guides: list) -> None:
    payload = (
        "/* Generated by scripts/build_static.py from data/*.json — edit those, then rebuild. */\n"
        f"window.EVENT = {json.dumps(event, indent=2, ensure_ascii=False)};\n\n"
        f"window.GUIDES = {json.dumps(guides, indent=2, ensure_ascii=False)};\n"
    )
    (STATIC / "js" / "data.js").write_text(payload, encoding="utf-8")
    print(f"  data.js       {len(payload) / 1024:6.1f} KB")


def inline_assets(html: str) -> str:
    stylesheet = re.compile(r'<link rel="stylesheet" href="([^"]+)"\s*/?>')
    script = re.compile(r'<script src="([^"]+)"></script>')

    def read_asset(href: str) -> str:
        path = (STATIC / href).resolve()
        if not path.is_file():
            raise SystemExit(f"Missing asset: {path}")
        return path.read_text(encoding="utf-8")

    def replace_css(match: re.Match) -> str:
        return f"<style>\n{read_asset(match.group(1))}\n</style>"

    def replace_js(match: re.Match) -> str:
        code = read_asset(match.group(1))
        # A literal "</script" inside JS would end the inline block early.
        code = re.sub(r"</script", r"<\\/script", code, flags=re.IGNORECASE)
        return f"<script>\n{code}\n</script>"

    html = stylesheet.sub(replace_css, html)
    html = script.sub(replace_js, html)
    return html


def main() -> int:
    event = load_json(DATA / "event.json", {})
    guides = load_json(DATA / "guides.json", [])
    print("\n  Building the static Christmas Thing")
    print("  " + "─" * 44)

    write_data_js(event, guides)

    index = STATIC / "index.html"
    html = inline_assets(index.read_text(encoding="utf-8"))
    DIST.parent.mkdir(parents=True, exist_ok=True)
    DIST.write_text(html, encoding="utf-8")

    print(f"  dist file     {len(html) / 1024:6.1f} KB")
    print(f"  → {DIST.relative_to(ROOT)}")
    print("  " + "─" * 44)
    print("  Open it directly, or upload it anywhere.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
